-- ===== smf: team, settings, photo bucket =====

-- ใครทำอะไรในปีนี้ ที่เดียว: admin = ดูแล Setting (CFO: ผู้จัดทำ), chairman = ประธาน / หัวหน้าทีมตรวจ, vice = รองประธาน,
-- auditor = ผู้ตรวจในทีม A–Z, owner = เจ้าของพื้นที่ (area_id) ปีละ 1 คนต่อพื้นที่,
-- member = ตัวแทนหน่วยงาน (department) 1 คนดูแลได้หลายหน่วยงาน
create table if not exists public.mt_smf_team (
  id bigint generated by default as identity primary key,
  year integer not null check (year between 2000 and 2100),
  employee_id text not null,
  role text not null,
  team text check (team ~ '^[A-Z]$'),
  area_id bigint,
  department text,
  status text not null default 'Active' check (status in ('Active', 'Inactive')),
  constraint mt_smf_team_auditor_has_team check ((role = 'auditor') = (team is not null)),
  constraint mt_smf_team_owner_has_area check ((role = 'owner') = (area_id is not null))
);
alter table public.mt_smf_team add column if not exists department text;
-- unit = ทีมย่อยของกิจกรรม (ผู้ใช้กำหนด 2026-10-30) · ว่าง = คณะกรรมการกลาง (ประธาน · รองประธาน · ที่ปรึกษา · ผู้ประสานงาน)
-- 5S: standard ทีมมาตรฐาน · academic ทีมวิชาการ · pr ทีมประชาสัมพันธ์ · audit ทีมตรวจประเมิน (+ ผู้รับผิดชอบพื้นที่ / ผู้ตรวจ) · server ตรวจค่า
alter table public.mt_smf_team add column if not exists unit text;
alter table public.mt_smf_team
  drop constraint if exists mt_smf_team_role_check,
  drop constraint if exists mt_smf_team_member_has_dept,
  drop constraint if exists mt_smf_team_unique;
-- ร่างเดิมเก็บชื่อทีมย่อยเป็นบทบาท: ย้ายเป็นสมาชิกของทีมนั้น (รันซ้ำได้)
update public.mt_smf_team set unit = role, role = 'member' where role in ('standard', 'academic', 'pr');
alter table public.mt_smf_team
  add constraint mt_smf_team_role_check check (role in ('admin', 'chairman', 'vice', 'advisor', 'smart', 'auditor', 'owner', 'member')),
  -- สมาชิก = ตัวแทนหน่วยงาน (department) หรือสมาชิกของทีมย่อย (unit) · บทบาทอื่นไม่มีหน่วยงาน
  add constraint mt_smf_team_member_has_dept check (case when role = 'member' then department is not null or unit is not null else department is null end),
  add constraint mt_smf_team_unique unique nulls not distinct (year, employee_id, role, unit, team, area_id, department);
create index if not exists mt_smf_team_lookup on public.mt_smf_team (year, employee_id);
create unique index if not exists mt_smf_team_one_owner on public.mt_smf_team (year, area_id) where role = 'owner';

create table if not exists public.mt_smf_setting (
  key text primary key,
  value text not null
);

-- ที่เก็บรูปของกิจกรรมนี้ (Supabase Storage) ชื่อ img_smf · รูป JPEG ≤ 700 KB เปิดดูได้ด้วยลิงก์
-- ข้ามไปเองถ้าฐานไม่มี storage (เช่นตอนทดสอบด้วย PGlite)
do $$ begin
  if to_regclass('storage.buckets') is not null then
    insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
    values ('img_smf', 'img_smf', true, 716800, array['image/jpeg'])
    on conflict (id) do nothing;
  end if;
end $$;

-- ===== smf: Project Planner =====

-- ข้อหลัก (parent_id ว่าง) และข้อรอง (parent_id = ข้อหลัก) ลึก 2 ระดับ (server ตรวจ) · ลบข้อหลักแล้วข้อรองหายด้วย
-- ข้อหลักที่มีข้อรอง: ช่วงวันและ % คิดจากข้อรอง (server) ค่าที่เก็บในแถวข้อหลักไม่ใช้
create table if not exists public.mt_smf_task (
  id bigint generated by default as identity primary key,
  year integer not null check (year between 2000 and 2100),
  parent_id bigint references public.mt_smf_task (id) on delete cascade,
  sort_no integer not null default 1,
  title text not null,
  start_date date,
  end_date date,
  progress integer not null default 0 check (progress between 0 and 100),
  owner_id text,                                          -- employee_id (Mx Data)
  color text,                                             -- สีของข้อหลัก p1–p12
  note text,
  created_by text not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint mt_smf_task_dates check ((start_date is null) = (end_date is null) and end_date >= start_date),
  constraint mt_smf_task_sub_has_dates check (parent_id is null or start_date is not null)
);
create index if not exists mt_smf_task_year on public.mt_smf_task (year, parent_id, sort_no);
-- วันที่ทำครบ 100% (server ใส่ให้) ใช้บอกเสร็จก่อนแผน / ตามแผน / ช้า เทียบกับ end_date · เพิ่มทีหลัง จึงใช้ add column (รันซ้ำได้)
alter table public.mt_smf_task add column if not exists done_on date;
-- โครงการ / ทีมย่อยของข้อหลัก (SMF: mt_smf_project.code) · ข้อรองตามข้อหลัก (ผู้ใช้กำหนด 2026-11-01)
alter table public.mt_smf_task add column if not exists unit text;

-- ===== smf: โครงการรายปี =====

create table if not exists public.mt_smf_project (
  id bigint generated by default as identity primary key,
  year integer not null check (year between 2000 and 2100),
  code text not null check (code ~ '^[a-z0-9_-]{1,20}$'),      -- ใช้ใน mt_smf_team.unit / mt_smf_task.unit
  name text not null,
  sort_no integer not null default 1,
  status text not null default 'Active' check (status in ('Active', 'Inactive')),
  unique (year, code)
);
