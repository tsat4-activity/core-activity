-- % ของแต่ละหมวดต่อใบตรวจ (Summary / Ranking) · security_invoker = ใช้สิทธิ์ของคนเรียก ไม่ข้าม RLS
create or replace view public.v_5s_audit_group with (security_invoker = true) as
select s.audit_id, c.s_group,
  sum(s.score) as score,
  sum(c.score_max) as score_max,
  round(sum(s.score) * 100.0 / nullif(sum(c.score_max), 0), 2) as percent
from public.tx_5s_audit_score s
join public.mt_5s_checklist c on c.id = s.checklist_id
group by s.audit_id, c.s_group;

