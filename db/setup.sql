-- ===== 5s: team, settings, photo bucket =====

-- ใครทำอะไรในปีนี้ ที่เดียว: admin = ดูแล Setting (CFO: ผู้จัดทำ), chairman = ประธาน / หัวหน้าทีมตรวจ, vice = รองประธาน,
-- auditor = ผู้ตรวจในทีม A–Z, owner = เจ้าของพื้นที่ (area_id) ปีละ 1 คนต่อพื้นที่,
-- member = ตัวแทนหน่วยงาน (department) 1 คนดูแลได้หลายหน่วยงาน
create table if not exists public.mt_5s_team (
  id bigint generated by default as identity primary key,
  year integer not null check (year between 2000 and 2100),
  employee_id text not null,
  role text not null,
  team text check (team ~ '^[A-Z]$'),
  area_id bigint,
  department text,
  status text not null default 'Active' check (status in ('Active', 'Inactive')),
  constraint mt_5s_team_auditor_has_team check ((role = 'auditor') = (team is not null)),
  constraint mt_5s_team_owner_has_area check ((role = 'owner') = (area_id is not null))
);
alter table public.mt_5s_team add column if not exists department text;
alter table public.mt_5s_team
  drop constraint if exists mt_5s_team_role_check,
  add constraint mt_5s_team_role_check check (role in ('admin', 'chairman', 'vice', 'advisor', 'smart', 'auditor', 'owner', 'member')),
  drop constraint if exists mt_5s_team_member_has_dept,
  add constraint mt_5s_team_member_has_dept check ((role = 'member') = (department is not null)),
  drop constraint if exists mt_5s_team_unique,
  add constraint mt_5s_team_unique unique nulls not distinct (year, employee_id, role, team, area_id, department);
create index if not exists mt_5s_team_lookup on public.mt_5s_team (year, employee_id);
create unique index if not exists mt_5s_team_one_owner on public.mt_5s_team (year, area_id) where role = 'owner';

